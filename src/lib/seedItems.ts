export function buildSeedItems(): Item[] {
  const out: Item[] = [];
  let i = 0;
  for (const group of seed) {
    for (const name of group.names) {
      out.push({
        id: `seed-${i++}`,
        name,
        category: group.category,
        safetyStock: 0,
        active: true,
        createdAt: Date.now() + i,
        type: "quantity",
      });
    }
  }
  return out;
}
